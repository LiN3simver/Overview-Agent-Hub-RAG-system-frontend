"""Lock the verified Python 3.12 environment for Windows and Linux.

Run after installing/reviewing requirements-dev.in in a disposable environment.
No upgrades are performed. Hashes come only from the exact releases on PyPI.
"""
from __future__ import annotations

import importlib.metadata as metadata
import json
import sys
from pathlib import Path
from urllib.request import urlopen

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]


def inputs(path):
    result = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line.startswith("-r "):
            result.extend(inputs(path.parent / line[3:].strip()))
        elif line:
            result.append(Requirement(line))
    return result


def resolve(roots, platform):
    env = default_environment()
    env.update(python_version="3.12", python_full_version="3.12.0",
               sys_platform=platform, platform_system="Windows" if platform == "win32" else "Linux",
               platform_python_implementation="CPython", implementation_name="cpython")
    explicit = {canonicalize_name(r.name): next(iter(r.specifier)).version for r in roots
                if len(r.specifier) == 1 and next(iter(r.specifier)).operator == "=="}
    found, visited, pending = {}, set(), list(roots)
    while pending:
        req = pending.pop()
        if req.marker and not req.marker.evaluate({**env, "extra": ""}):
            continue
        name = canonicalize_name(req.name)
        version = explicit.get(name) or metadata.version(name)
        if version not in req.specifier:
            raise ValueError(f"{name}=={version} does not satisfy {req}")
        key = (name, tuple(sorted(req.extras)))
        found[name] = (version, set(req.extras) | found.get(name, (None, set()))[1])
        if key in visited:
            continue
        visited.add(key)
        try:
            dist = metadata.distribution(name)
            if dist.version != version:
                raise ValueError(f"Install the reviewed {name}=={version} before locking")
            dependencies = dist.requires or []
        except metadata.PackageNotFoundError:
            if name != "uvloop":
                raise
            dependencies = release(name, version)["info"]["requires_dist"] or []
        for text in dependencies:
            dep = Requirement(text)
            if dep.marker and not any(dep.marker.evaluate({**env, "extra": extra})
                                      for extra in ("", *req.extras)):
                continue
            dep.marker = None
            pending.append(dep)
    return found


CACHE = {}


def release(name, version):
    key = (name, version)
    if key not in CACHE:
        with urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
            CACHE[key] = json.load(response)
    return CACHE[key]


def render(platforms, excluded=()):
    lines = ["# Generated by scripts/lock_dependencies.py; Python 3.12 Windows/Linux.",
             "# Review .in files and the lock diff together. Do not edit hashes.", "--require-hashes"]
    if excluded:
        lines.append("-r requirements.txt")
    for name in sorted(set().union(*(set(p) for p in platforms.values())) - set(excluded)):
        entries = [p[name] for p in platforms.values() if name in p]
        versions = {entry[0] for entry in entries}
        if len(versions) != 1:
            raise ValueError(f"Different platform versions for {name}")
        version = versions.pop()
        extras = sorted(set().union(*(entry[1] for entry in entries)))
        suffix = "[" + ",".join(extras) + "]" if extras else ""
        marker = ""
        if len(entries) != len(platforms):
            marker = "; " + " or ".join(f'sys_platform == "{key}"' for key, p in platforms.items() if name in p)
        hashes = sorted({item["digests"]["sha256"] for item in release(name, version)["urls"]
                         if not item["yanked"]})
        if not hashes:
            raise ValueError(f"No non-yanked artifacts: {name}=={version}")
        lines.append(f"{name}{suffix}=={version}{marker} \\")
        lines.extend("    --hash=sha256:" + value + (" \\" if index < len(hashes) - 1 else "")
                     for index, value in enumerate(hashes))
    return "\n".join(lines) + "\n"


def main():
    if sys.version_info[:2] != (3, 12):
        raise SystemExit("Lock dependencies using Python 3.12.")
    runtime = {p: resolve(inputs(ROOT / "requirements.in"), p) for p in ("win32", "linux")}
    development = {p: resolve(inputs(ROOT / "requirements-dev.in"), p) for p in ("win32", "linux")}
    # Resolve both before writing either file; do not leave a partial dependency closure.
    runtime_text = render(runtime)
    development_text = render(development, set().union(*(set(p) for p in runtime.values())))
    (ROOT / "requirements.txt").write_text(runtime_text, encoding="utf-8")
    (ROOT / "requirements-dev.txt").write_text(development_text, encoding="utf-8")
    print("Locked runtime and development dependencies (Windows/Linux, Python 3.12).")


if __name__ == "__main__":
    main()
